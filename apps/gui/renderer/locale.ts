export function detectLocale(language: string | undefined): Locale {
  return language?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function initialLocale(): Locale {
  try {
    const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    if (stored === "en" || stored === "zh-CN") return stored;
  } catch {
    // Storage can be unavailable in restricted renderer contexts.
  }
  return detectLocale(window.navigator.language);
}

export function localizedNotice(notice: string, locale: Locale): string {
  const words = copy[locale];
  const exact: Record<string, string> = {
    "Manual mode: every reply needs explicit confirmation.": words.manualNotice,
    "Receiving PCM; decoder and reply model are running in the existing receive session.": words.receivingNotice,
    "New receive text invalidated the previous reply proposal.": words.newTextNotice,
    "Validated reply proposal; no transmission was performed.": words.validatedNotice,
    "No reply was proposed for the latest receive context.": words.noReplyNotice,
    "The latest receive event did not produce a dispatchable reply.": words.invalidReplyNotice,
    "The previous reply proposal was invalidated by new receive context.": words.invalidatedNotice,
    "Receive failed.": words.receiveFailedNotice,
    "Listening to live audio; no transmission is enabled.": words.liveNotice,
    "Automatic mode is on, but no reply proposal is available.": words.autoNoProposalNotice,
    "Editing paused automatic dispatch; this session is manual. The edited text is not sent by this demo slice.": words.editingNotice,
    "Automatic dispatch eligibility revoked for the current proposal.": words.revokedNotice,
    "Stopped. This session is terminal; restart the app for a new session.": words.stoppedNotice,
  };
  if (exact[notice] !== undefined) return exact[notice];
  const armed = notice.match(/^Automatic dispatch armed for the current (local-cq|ai) proposal\.$/);
  if (armed) return words.autoArmedNotice(armed[1] === "ai" ? words.sourceAi : words.sourceLocal);
  if (notice.startsWith("Automatic mode is on, but this proposal cannot be dispatched")) return words.autoUnavailableNotice;
  return notice;
}
